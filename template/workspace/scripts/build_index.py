#!/usr/bin/env python3
"""Rebuild index.md in every workspace folder and the root, from frontmatter.

Run after every change: python3 scripts/build_index.py
The LLM writes `summary:` into each file's frontmatter; this script turns that into indexes,
so the indexes never drift from the files.
"""
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP_DIRS = {".git", "scripts", ".obsidian", "research", "vendor", "icons", "data"}  # research has its own READMEs; the rest hold no notes
SKIP_FILES = {"CLAUDE.md", "AGENTS.md", "index.md"}
TIME_DIRS = {"inbox", "daily", "weekly", "journal"}  # dated files: show recent only
PRIVATE_DIRS = {"journal"}  # never put summaries of these in an index
RECENT = 14


def frontmatter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8", errors="replace")
    meta = {}
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if m:
        for line in m.group(1).splitlines():
            if ":" in line and not line.startswith(" "):
                k, v = line.split(":", 1)
                meta[k.strip()] = re.split(r"\s#", v)[0].strip().strip('"')  # a YAML comment needs a space before #; "PR #88" stays
        text = text[m.end():]
    if not meta.get("summary"):
        first = next((l for l in text.splitlines() if l.strip()), "")
        meta["summary"] = first.lstrip("# ").strip()[:120]
    return meta


def folder_purpose(d: Path) -> str:
    c = d / "CLAUDE.md"
    if not c.exists():
        return ""
    lines = [l.strip() for l in c.read_text(encoding="utf-8").splitlines() if l.strip()]
    return next((l for l in lines[1:] if not l.startswith(("#", "-", "|", "`"))), "")[:140]


def cell(s: str) -> str:
    """Table-safe text: no pipes, first sentence only."""
    s = re.sub(r"[\x00-\x1f\x7f\u2028\u2029]", " ", s.replace("|", "/"))
    return re.sub(r"\s+", " ", s).split(". ")[0][:120]


TYPES = {"person", "project", "topic", "goal", "glossary", "decision", "me", "style", "source", "idea", "learning"}
RELATIONS = {"manager", "report", "skip-level", "peer", "stakeholder", "freelancer", "external"}
TOPIC_STATUS = {"active", "complete", "parked"}
STATUSES = {"current", "draft", "superseded", "open", "doing", "done", "parked"}


def only(value: str, allowed: set[str]) -> str:
    # ingested sources may carry crafted frontmatter: emit known values only
    return value if value in allowed else ""


def date_or_blank(value: str) -> str:
    return value if re.fullmatch(r"\d{4}-\d{2}-\d{2}", value) else ""


def md_files(d: Path) -> list[Path]:
    return sorted(p for p in d.glob("*.md") if p.name not in SKIP_FILES)


def subdirs(d: Path) -> list[Path]:
    return sorted(p for p in d.iterdir() if p.is_dir() and p.name not in SKIP_DIRS)


def count_md(d: Path) -> int:
    return sum(1 for p in d.rglob("*.md") if p.name not in SKIP_FILES and ".git" not in p.parts)


def build_folder(d: Path) -> str:
    rel = d.relative_to(ROOT).as_posix()
    out = [f"# Index: {rel}/", "", "Generated by `scripts/build_index.py`. Do not edit by hand.", ""]
    if purpose := folder_purpose(d):
        out += [purpose, ""]
    if subs := subdirs(d):
        out += ["## Subfolders", ""] + [f"- [[{s.relative_to(ROOT).as_posix()}/index|{s.name}/]] ({count_md(s)} files)" for s in subs] + [""]
    files = md_files(d)
    top = d.relative_to(ROOT).parts[0] if d != ROOT else ""
    if top in TIME_DIRS:
        # weekly files are YYYY-Www: group them by year (stem[:7] would cut "2026-W45" to "2026-W4")
        weekly = bool(files) and all(re.fullmatch(r"\d{4}-W\d{2}", p.stem) for p in files)
        months = Counter(p.stem[:4] if weekly else p.stem[:7] for p in files)
        out += ["## Recent", ""]
        for p in files[-RECENT:][::-1]:
            summary = "" if top in PRIVATE_DIRS else f": {cell(frontmatter(p)['summary'])}"
            out.append(f"- [[{p.relative_to(ROOT).with_suffix('').as_posix()}|{p.stem}]]{summary}")
        out += ["", "## By year" if weekly else "## By month", ""] + [f"- {m}: {n}" for m, n in sorted(months.items(), reverse=True)]
    elif files:
        people = rel == "context/people"  # people also show role, relation and the close flag
        out += ["## Files", "", "| File | Summary | Type | Status | Updated |" + (" Role | Relation | Close |" if people else ""), "|---|---|---|---|---|" + ("---|---|---|" if people else "")]
        for p in files:
            fm = frontmatter(p)
            link = f"[[{p.relative_to(ROOT).with_suffix('').as_posix()}\\|{p.stem}]]"  # \\| = pipe escaped for Obsidian tables
            row = f"| {link} | {cell(fm['summary'])} | {only(fm.get('type', ''), TYPES)} | {only(fm.get('status', ''), STATUSES)} | {date_or_blank(fm.get('updated', ''))} |"
            if people:
                row += f" {cell(fm.get('role', ''))} | {only(fm.get('relation', ''), RELATIONS)} | {only(fm.get('close', ''), {'true', 'false'})} |"
            out.append(row)
    return "\n".join(out) + "\n"


def build_root() -> str:
    out = ["# Index", "", "Start here. Generated by `scripts/build_index.py`. Read order: `CLAUDE.md`, this file, the folder index, then the page.", "", "| Folder | Files | Purpose |", "|---|---|---|"]
    research = ROOT / "research"  # skipped by the folder index (it has its own READMEs), but navigation still reaches it
    for s in sorted(subdirs(ROOT) + ([research] if research.is_dir() else []), key=lambda p: p.name):
        out.append(f"| [[{s.name}/index\\|{s.name}/]] | {count_md(s)} | {cell(folder_purpose(s))} |")
    out += ["", "Top-level files: " + ", ".join(f"[[{p.stem}]]" for p in md_files(ROOT))]
    return "\n".join(out) + "\n"


def build_research() -> str:
    """research/index.md: one row per topic folder (active and archived), so the root can link a catalogue without indexing topic internals."""
    out = ["# Index: research/", "", "Generated by `scripts/build_index.py`. Do not edit by hand.", "", "One folder per topic; its README is the entry point. Rules: `research/CLAUDE.md`.", "",
           "| Topic | Status | Where |", "|---|---|---|"]
    for scope, where in ((ROOT / "research", "active"), (ROOT / "research" / "_archive", "archive")):
        for t in sorted(p for p in scope.glob("*") if p.is_dir() and not p.name.startswith("_")) if scope.is_dir() else []:
            m = re.search(r"\*\*Status:\*\*\s*(\w+)", (t / "README.md").read_text(encoding="utf-8", errors="replace")) if (t / "README.md").exists() else None
            out.append(f"| [[{t.relative_to(ROOT).as_posix()}/README\\|{t.name}]] | {only(m.group(1).lower(), TOPIC_STATUS) if m else ''} | {where} |")
    return "\n".join(out) + "\n"


def hand_written(d: Path) -> bool:
    """A folder whose index.md is real content (context/areas/), not a generated index: leave it alone."""
    f = d / "index.md"
    return f.exists() and not f.read_text(encoding="utf-8").startswith("# Index")


def main() -> None:
    dirs = [d for d in ROOT.rglob("*") if d.is_dir() and not (set(d.relative_to(ROOT).parts) & SKIP_DIRS)]
    for d in dirs:
        if not hand_written(d):
            (d / "index.md").write_text(build_folder(d), encoding="utf-8")
    if (ROOT / "research").is_dir():
        (ROOT / "research" / "index.md").write_text(build_research(), encoding="utf-8")
    (ROOT / "index.md").write_text(build_root(), encoding="utf-8")
    # self-check: every non-dated, non-private file is listed in its folder index
    for d in dirs:
        if d.relative_to(ROOT).parts[0] in TIME_DIRS or hand_written(d):
            continue
        idx = (d / "index.md").read_text(encoding="utf-8")
        missing = [p.name for p in md_files(d) if f"|{p.stem}]]" not in idx and f"\\|{p.stem}]]" not in idx]
        assert not missing, f"{d}: not indexed: {missing}"
    print(f"indexed {len(dirs)} folders")


if __name__ == "__main__":
    sys.exit(main())
